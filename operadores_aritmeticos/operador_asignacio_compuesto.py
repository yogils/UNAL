#Operador asignación compuesto
print("Operador asignación compuesto")
x = 10
print(f"Valor inicial de x: {x}")
x += 5
print(f"Valor de x después de x += 5: {x}")
x -= 3
print(f"Valor de x después de x -= 3: {x}")     
x *= 10
print(f"Valor de x después de x *= 10: {x}")
x /= 2
print(f"Valor de x después de x /= 2: {x}")
x %= 4
print(f"Valor de x después de x %= 4: {x}")
x **= 3
print(f"Valor de x después de x **= 3: {x}")