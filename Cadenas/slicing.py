#slicing pruebas
cadena = "Esto es una prueba de slicing en python"
print("Cadena original:", cadena)

#Acceder a un solo caracter
print("Primer caracter:", cadena[0])  # Primer caracter
print("Ultimo caracter:", cadena[-1])  # Ultimo caracter

texto = "PROGRAMACION"
print("Texto original:", texto)
print("Primer caracter:", texto[0])
print("Ultimo caracter:", texto[-1])
print("Primeros 5 caracteres:", texto[0:5])  # Primeros 5 caracteres
print("Caracteres desde el 3 hasta el 7:", texto[2:7])  # Caracteres desde el 3 hasta el 7
print("cadena invertida:", texto[::-1])  # Cadena invertida